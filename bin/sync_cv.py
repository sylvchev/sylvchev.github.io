"""Sync the website with the LaTeX CV repository.

    uv run bin/sync_cv.py [CV_DIR]      # default: ~/admin/CV/CVadmin/CV_2026

Reads from the CV repo (never writes there):
  CV-Sylvain_Chevallier.pdf   -> cv/cv.pdf
  data/publications.bib       -> _bibliography/papers.bib  (+ _bibliography/extra.bib)
  data/supervision.yml        -> _data/supervision.yml     (English, via the *_en fields)
  \\fullcite keys in the .tex -> selected = {true} in papers.bib (about page)

papers.bib and _data/supervision.yml are generated: edit the CV repo or
_bibliography/extra.bib instead.
"""
import re
import shutil
import sys
from pathlib import Path

import yaml

CV_NAME = "CV-Sylvain_Chevallier"
SITE = Path(__file__).resolve().parent.parent
BANNER = "Generated by bin/sync_cv.py from the CV repository. Do not edit by hand."

MONTHS = dict(zip(
    "janvier février mars avril mai juin juillet août septembre octobre novembre décembre".split(),
    "January February March April May June July August September October November December".split(),
))
STATUS = {
    "starting": "Starts on",
    "ongoing": "Started on",
    "planned": "Defense planned on",
    "defended": "Defended on",
}
GROUPS = {"m2": "Master 2 interns", "other": "Other interns"}


def months(text):
    """'avril-septembre 2026' -> 'April–September 2026'."""
    for fr, en in MONTHS.items():
        text = re.sub(rf"\b{fr}\b", en, text)
    return re.sub(r"(?<=[A-Za-z0-9])-(?=[A-Z])", "–", text)


def date(text):
    """'1er octobre 2026' / '08 novembre 2024' -> 'October 1, 2026'."""
    m = re.fullmatch(r"(\d+)(?:er)? (\w+) (\d{4})", text.strip())
    return f"{MONTHS[m[2]]} {int(m[1])}, {m[3]}" if m else months(text)


def duration(text):
    """'3 ans et 3 mois, avec une suspension Covid' -> '3 years 3 months, including a Covid suspension'."""
    text = re.sub(r"(\d+) ans?", lambda m: f"{m[1]} year{'s' if m[1] != '1' else ''}", text)
    text = re.sub(r"(\d+) mois", lambda m: f"{m[1]} month{'s' if m[1] != '1' else ''}", text)
    return text.replace(" et ", " ").replace(", avec une suspension Covid", ", including a Covid suspension")


def plain(text):
    """Strip the few LaTeX idioms used in the YAML."""
    return text.replace("\\-", "").replace("\\%", "%").replace("''", "'")


def en(rec, field):
    value = rec.get(f"{field}_en", rec.get(field))
    if isinstance(value, list):
        return [plain(v) for v in value]
    return plain(str(value)) if value is not None else None


def supervision(src):
    data = yaml.safe_load(src.read_text(encoding="utf-8"))
    phd = []
    for r in data["phd"]:
        line = f"{STATUS[r['status']]} {date(r['date'])}"
        if r.get("duration"):
            line += f" ({duration(r['duration'])})"
        phd.append({
            "name": r["name"],
            "funding": en(r, "funding"),
            "supervision": f"{r['share']}% supervision, {en(r, 'cosupervision')}",
            "title": en(r, "title"),
            "status": line,
            "position": en(r, "position"),
            "ongoing": r["status"] != "defended",
        })
    interns = {label: [] for label in GROUPS.values()}
    for r in data["intern"]:
        if r.get("hidden"):
            continue
        where = ", ".join(x for x in (f"{en(r, 'level')} intern", en(r, "institution")) if x)
        details = [f"{where} ({months(r['period'])})"]
        if r.get("cosupervisors"):
            names = en(r, "cosupervisors")
            details.append("with " + (", ".join(names[:-1]) + " and " + names[-1] if len(names) > 1 else names[0]))
        if r.get("note"):
            details.append(en(r, "note"))
        interns[GROUPS[r["group"]]].append({"name": en(r, "name"), "details": ", ".join(details), "title": en(r, "title")})
    missing = [r["name"] for r in data["phd"] + data["intern"]
               if not r.get("hidden") and r.get("title") and "title_en" not in r
               and re.search(r"[éèàùç]|\b(des?|du|la|le|les|pour|avec|et)\b", r["title"])]
    return {"phd": phd, "interns": [{"group": k, "items": v} for k, v in interns.items()]}, missing


def bibliography(cv_bib, extra_bib, selected):
    bib = cv_bib.read_text(encoding="utf-8")
    bib = re.sub(r"\\enquote\{([^}]*)\}", r"“\1”", bib)
    found = set()
    for key in selected:
        bib, n = re.subn(rf"(@\w+\s*\{{\s*{re.escape(key)}\s*,\n)", r"\1  selected   = {true},\n", bib)
        if n:
            found.add(key)
    header = f"% {BANNER}\n% Source: {cv_bib.name} from the CV repo, then _bibliography/extra.bib.\n\n"
    return header + bib.rstrip() + "\n\n" + extra_bib.read_text(encoding="utf-8"), set(selected) - found


def main():
    cv = Path(sys.argv[1] if len(sys.argv) > 1 else "~/admin/CV/CVadmin/CV_2026").expanduser()
    pdf, tex = cv / f"{CV_NAME}.pdf", cv / f"{CV_NAME}.tex"
    sources = [tex, cv / "data/publications.bib", cv / "data/supervision.yml"]
    if max(p.stat().st_mtime for p in sources) > pdf.stat().st_mtime:
        print(f"warning: {pdf.name} is older than its sources, run `make` in {cv}", file=sys.stderr)

    shutil.copy2(pdf, SITE / "cv/cv.pdf")

    selected = re.findall(r"\\fullcite\{([^}]+)\}", tex.read_text(encoding="utf-8"))
    bib, unknown = bibliography(cv / "data/publications.bib", SITE / "_bibliography/extra.bib", selected)
    (SITE / "_bibliography/papers.bib").write_text(bib, encoding="utf-8")

    data, untranslated = supervision(cv / "data/supervision.yml")
    out = f"# {BANNER}\n" + yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=1000)
    (SITE / "_data/supervision.yml").write_text(out, encoding="utf-8")

    n_bib = bib.count("\n@")
    n_interns = sum(len(g["items"]) for g in data["interns"])
    print(f"cv/cv.pdf updated | papers.bib: {n_bib} entries, {len(selected) - len(unknown)} selected "
          f"| supervision: {len(data['phd'])} PhD, {n_interns} interns")
    for key in unknown:
        print(f"warning: selected key {key} not found in the bib", file=sys.stderr)
    for name in untranslated:
        print(f"warning: no title_en for {name}, French title shown on the website", file=sys.stderr)


if __name__ == "__main__":
    main()
